#!/usr/bin/env python3
"""Wrap the SDK's XZ radio firmware in the WLFW container and emit a C array.

WLFW container (as in the stock wififw partition): 'WLFW', u32 LE length of
the XZ stream, then the XZ stream.  The array lands in the XIP flash segment
of our app image, so the Wi-Fi driver can read it through a flash descriptor
pointing into our own appfw slot; the stock wififw partitions stay untouched.

usage: gen_wlfw.py FIRMWARE.bin.xz OUT.c
"""
import struct, sys

xz = open(sys.argv[1], "rb").read()
assert xz[:6] == b"\xfd7zXZ\x00", "not an XZ stream"
blob = b"WLFW" + struct.pack("<I", len(xz)) + xz
lines = []
for i in range(0, len(blob), 16):
    lines.append("\t" + ",".join(f"0x{b:02x}" for b in blob[i:i + 16]) + ",")
with open(sys.argv[2], "w") as f:
    f.write("/* generated by tools/gen_wlfw.py from %s - do not edit */\n"
            % sys.argv[1].split("/")[-1])
    f.write("#include <stdint.h>\n")
    f.write("__attribute__((aligned(4), used)) const uint8_t wlfw_embedded[%d] = {\n"
            % len(blob))
    f.write("\n".join(lines) + "\n};\n")
    f.write("const uint32_t wlfw_embedded_len = %d;\n" % len(blob))
