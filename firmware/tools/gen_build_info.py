#!/usr/bin/env python3
"""Write the link-time build stamp (U1); run by firmware/Makefile on every link.

    gen_build_info.py OUT.c OUT_EPOCH

OUT.c defines fw_build_time ("YYYY-MM-DD HH:MM:SS UTC", include/diag.h).
OUT_EPOCH holds the same second as a decimal Unix time, for
mrvl_pack.py --timestamp (the MRVL header).  SOURCE_DATE_EPOCH overrides
the clock (reproducible builds)."""
import os
import sys
import time


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    sde = os.environ.get("SOURCE_DATE_EPOCH")
    epoch = (int(sde) if sde else int(time.time())) & 0xFFFFFFFF   # 32-bit header field
    stamp = time.strftime("%Y-%m-%d %H:%M:%S UTC", time.gmtime(epoch))
    with open(sys.argv[1], "w") as f:
        f.write("/* generated by tools/gen_build_info.py on every link */\n"
                f'const char fw_build_time[] = "{stamp}";\n')
    with open(sys.argv[2], "w") as f:
        f.write(f"{epoch}\n")


if __name__ == "__main__":
    main()
